#!/usr/bin/env python3
"""One-off asset generator for the Wii port. Its output (source/font_data.c, icon.png) is committed, so building the
game does not need Python or Pillow; run this only to change the font or icon:  python3 tools/make_assets.py

Font: DejaVu Sans Bold (Bitstream Vera licence: free to embed and redistribute, see the README). 95 printable ASCII
glyphs (32..126) in a 16-column atlas, 4 bits of alpha per pixel (the game expands it to a GX IA4 texture), plus the
advance width of each glyph so text can be laid out proportionally."""
import sys, os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
CELL_W, CELL_H, COLS, ROWS, SIZE, BASE = 28, 36, 16, 6, 28, 28   # atlas 448x216 (both multiples of 8 and 4, as IA4 tiles need)

font = ImageFont.truetype(FONT, SIZE)
atlas = Image.new("L", (CELL_W * COLS, CELL_H * ROWS), 0)
adv = []
for i in range(95):
    ch = chr(32 + i)
    cx, cy = (i % COLS) * CELL_W, (i // COLS) * CELL_H
    d = ImageDraw.Draw(atlas)
    d.text((cx + 1, cy + BASE), ch, font=font, fill=255, anchor="ls")
    adv.append(min(CELL_W - 2, int(round(font.getlength(ch))) + 1))

W, H = atlas.size
px = atlas.load()
nibbles = bytearray()
for y in range(H):
    row = [px[x, y] >> 4 for x in range(W)]
    for x in range(0, W, 2):
        nibbles.append((row[x] << 4) | row[x + 1])

def carray(name, data, per=24):
    lines = [f"const unsigned char {name}[{len(data)}] = {{"]
    for i in range(0, len(data), per):
        lines.append("  " + ",".join(str(b) for b in data[i:i + per]) + ",")
    lines.append("};")
    return "\n".join(lines)

with open(os.path.join(ROOT, "source", "font_data.c"), "w") as f:
    f.write("/* Generated by tools/make_assets.py from DejaVu Sans Bold. Do not edit by hand. */\n")
    f.write('#include "font_data.h"\n')
    f.write(carray("font_alpha4", nibbles) + "\n")
    f.write(carray("font_advance", bytes(adv)) + "\n")
with open(os.path.join(ROOT, "source", "font_data.h"), "w") as f:
    f.write(f"""#ifndef FONT_DATA_H
#define FONT_DATA_H
/* Generated by tools/make_assets.py. 4-bit alpha atlas, two pixels per byte (high nibble first), row-major. */
#define FONT_CELL_W {CELL_W}
#define FONT_CELL_H {CELL_H}
#define FONT_COLS {COLS}
#define FONT_BASE {BASE}
#define FONT_ATLAS_W {W}
#define FONT_ATLAS_H {H}
extern const unsigned char font_alpha4[{len(nibbles)}];
extern const unsigned char font_advance[95];
#endif
""")

# Homebrew Channel icon: 128x48.
icon = Image.new("RGB", (128, 48), (20, 24, 52))
d = ImageDraw.Draw(icon)
for y in range(48):
    d.line([(0, y), (128, y)], fill=(30 + y, 60 + y * 2, 140 + y))
for (x, y, c) in [(18, 16, (255, 90, 90)), (46, 10, (255, 210, 60)), (78, 18, (90, 220, 130)), (106, 11, (120, 170, 255))]:
    d.ellipse((x - 9, y - 11, x + 9, y + 11), fill=c, outline=(255, 255, 255))
    d.line([(x, y + 11), (x - 2, y + 22)], fill=(235, 235, 235))
big = ImageFont.truetype(FONT, 17)
small = ImageFont.truetype(FONT, 14)
d.text((64, 30), "Owen's", font=big, fill=(255, 255, 255), anchor="mm", stroke_width=2, stroke_fill=(20, 24, 52))
d.text((64, 43), "Minigames", font=small, fill=(255, 235, 120), anchor="mm", stroke_width=2, stroke_fill=(20, 24, 52))
icon.save(os.path.join(ROOT, "icon.png"))
print("atlas", W, "x", H, "->", len(nibbles), "bytes; wrote font_data.c/.h and icon.png")
